const toStrokes = (raw: Raw): Stroke[] => raw.map((s) => s.map(([x, y]) => ({ x, y })));

export function getStrokes(item: Item): Stroke[][] {
  const n = Number(item.id.split('-')[1]);
  if (item.island === 'ar') return [toStrokes(AR[n - 1])];
  if (item.island === 'en') return [toStrokes(EN[n - 1])];
  if (item.island === 'num') return String(item.count).split('').map((d) => toStrokes(DIGITS[Number(d)]));
  return [];
}
